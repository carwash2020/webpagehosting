// Small color-coded attribution dot -- blue for Connor, pink for Steve.
// Used anywhere a record shows who last touched it (Job Tracker, Invoice
// Generator, Parts & Reference / Appliance Wiki, Dev Tools). Consolidated
// here on 2026-08-14 -- it used to be copy-pasted separately into all 4
// files, so the color map had to be updated in 4 places if it ever
// changed. Now there's just one. Only renders for a real, known account
// email; anything else gets no dot rather than a wrong guess. `label` is
// an optional verb prefix for the tooltip (e.g. "Last edited by",
// "Generated by") -- omit it for a bare-email tooltip.
const PERSON_DOT_COLORS = {
  'connor@triplehenterprisesllc.biz': '#7ec4ff',
  'steve@triplehenterprisesllc.biz': '#f0a8c8',
};
function personDot(email, label) {
  const color = PERSON_DOT_COLORS[(email || '').toLowerCase()];
  if (!color) return '';
  const safeEmail = typeof escapeHtml === 'function' ? escapeHtml(email) : email;
  const title = label ? (label + ' ' + safeEmail) : safeEmail;
  return '<span style="display:inline-block; width:7px; height:7px; border-radius:50%; background:' + color + '; margin-right:5px; vertical-align:middle;" title="' + title + '"></span>';
}

