// Generic collapsed-icon search: a magnifying-glass button that expands
// into the real search input when tapped, and collapses back to just the
// icon if it loses focus while still empty -- keeps a page's toolbar
// compact until a search is actually wanted, everywhere this pattern is
// used across the app.
function toggleIconSearch(wrapId, forceOpen) {
  const wrap = document.getElementById(wrapId);
  if (!wrap) return;
  const input = wrap.querySelector('input');
  const shouldOpen = forceOpen !== undefined ? forceOpen : !wrap.classList.contains('is-expanded');
  if (shouldOpen) {
    wrap.classList.add('is-expanded');
    if (input) setTimeout(() => input.focus(), 50);
  } else {
    wrap.classList.remove('is-expanded');
  }
}
document.addEventListener('focusout', (e) => {
  const wrap = e.target.closest && e.target.closest('.icon-search');
  if (!wrap) return;
  setTimeout(() => {
    if (wrap.contains(document.activeElement)) return;
    const input = wrap.querySelector('input');
    if (input && !input.value.trim()) wrap.classList.remove('is-expanded');
  }, 120);
});

// Generic collapse/expand for "Add X"-style form sections -- used across
// multiple tool pages so a form starts collapsed and the page opens
// showing actual data first, rather than an empty form.
// Fades and collapses ONE specific row before its underlying data
// actually gets deleted and the list re-renders -- called from a real
// delete-button click, never from a render/filter pass, so this can
// never fire on every keystroke the way animating the whole list would.
// Measures the row's own real height first rather than guessing a fixed
// value, since these rows vary in height (wrapped text, extra fields).
function animateRowExit(rowElement, onComplete) {
  if (!rowElement) { onComplete(); return; }
  const reduceMotion = window.matchMedia && window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (reduceMotion) { onComplete(); return; }
  const isTableRow = rowElement.tagName === 'TR';
  // A <tr>'s rendered height is governed by the table layout algorithm,
  // not the normal box model -- max-height doesn't actually shrink a
  // table row's real height the way it does for a div, even though the
  // computed style itself transitions fine. Verified this directly
  // rather than assuming: for a <tr>, fall back to an opacity-only fade
  // instead of a collapse that would look subtly broken (correctly
  // fading, but leaving an empty gap where the row's height should be
  // shrinking) rather than actually smooth.
  if (isTableRow) {
    rowElement.style.transition = 'opacity .22s ease';
    requestAnimationFrame(() => { requestAnimationFrame(() => { rowElement.style.opacity = '0'; }); });
    setTimeout(onComplete, 230);
    return;
  }
  const height = rowElement.scrollHeight;
  rowElement.style.maxHeight = height + 'px';
  rowElement.style.overflow = 'hidden';
  rowElement.style.transition = 'opacity .22s ease, max-height .22s ease, margin .22s ease, padding .22s ease, border-width .22s ease';
  // Two rAFs, not one -- the browser needs to actually paint the
  // starting max-height (the row's real current height) as a distinct
  // frame before the target value changes, or the transition has
  // nothing to animate from and just snaps straight to the end state.
  requestAnimationFrame(() => {
    requestAnimationFrame(() => {
      rowElement.style.opacity = '0';
      rowElement.style.maxHeight = '0px';
      rowElement.style.marginTop = '0';
      rowElement.style.marginBottom = '0';
      rowElement.style.paddingTop = '0';
      rowElement.style.paddingBottom = '0';
      rowElement.style.borderWidth = '0';
    });
  });
  setTimeout(onComplete, 230);
}

// Swipe right anywhere on the page navigates back to Workspace, mirroring
// the native "swipe back" gesture already familiar from the rest of the
// phone. Content follows the finger in real time rather than only
// reacting after the gesture ends, and either completes the slide-away
// or springs back smoothly depending on whether the swipe actually
// cleared the threshold -- the same feel as a native back-swipe, not a
// binary "did this count or not" check with no feedback in between.
//
// Skips touches that start inside a <table> (a wide table on a narrow
// phone may need its own horizontal scroll), inside a <canvas> (signing
// a contract means dragging a finger across one, which can easily read
// as a horizontal swipe to this same detector -- without this exclusion,
// an in-progress signature gets silently aborted mid-stroke by a
// navigation neither the code nor the person intended), or while a modal
// is open. The modal case matters mechanically, not just visually:
// applying a transform to body creates a new containing block, which
// breaks position:fixed for every descendant -- an open modal would
// start moving with the page instead of staying fixed to the viewport.
function setupSwipeBackToWorkspace() {
  let touchStartX = 0, touchStartY = 0, touchStartTime = 0;
  let dragging = false, committed = false, visuallyDragged = false;
  const DRAG_ELEMENT = document.body;
  const THRESHOLD = 60;
  const MAX_DRAG = 140; // caps how far content visually follows the finger, even on a much longer drag

  function anyModalOpen() {
    return !!document.querySelector('.help-modal-overlay.is-open');
  }

  document.body.addEventListener('touchstart', (e) => {
    if (e.touches.length !== 1) return;
    touchStartX = e.touches[0].clientX;
    touchStartY = e.touches[0].clientY;
    touchStartTime = Date.now();
    dragging = !(e.target.closest && (e.target.closest('table') || e.target.closest('canvas'))) && !anyModalOpen();
    committed = false;
    visuallyDragged = false;
  }, { passive: true });

  document.body.addEventListener('touchmove', (e) => {
    if (!dragging || !e.touches.length) return;
    // A real signature is usually several separate strokes, lifted and
    // re-touched between letters -- checking only where a stroke started
    // isn't enough, since finger imprecision means any single stroke
    // could start a pixel outside the canvas's exact bounds and still be
    // part of the same signature. Checking continuously here means the
    // moment a drag crosses onto a canvas or table at all, swipe
    // detection cancels immediately, not just when it started there.
    if (e.target.closest && (e.target.closest('canvas') || e.target.closest('table'))) {
      dragging = false;
      DRAG_ELEMENT.style.transition = '';
      DRAG_ELEMENT.style.transform = '';
      DRAG_ELEMENT.style.opacity = '';
      return;
    }
    const dx = e.touches[0].clientX - touchStartX;
    const dy = e.touches[0].clientY - touchStartY;
    if (Math.abs(dx) < Math.abs(dy) * 1.5 || dx < 0) return; // not a rightward, mostly-horizontal drag -- leave scrolling alone
    const clamped = Math.min(dx, MAX_DRAG);
    visuallyDragged = true;
    DRAG_ELEMENT.style.transition = 'none';
    DRAG_ELEMENT.style.transform = `translateX(${clamped}px)`;
    DRAG_ELEMENT.style.opacity = String(1 - (clamped / MAX_DRAG) * 0.35);
  }, { passive: true });

  document.body.addEventListener('touchend', (e) => {
    if (!dragging || !visuallyDragged || !e.changedTouches.length) return;
    dragging = false;
    // Also check where the gesture ended, not just where it started or
    // passed through -- belt-and-suspenders with the touchmove check
    // above, since touchend's target can occasionally differ from the
    // last touchmove's target right at the boundary of an element.
    if (e.target.closest && (e.target.closest('canvas') || e.target.closest('table'))) {
      DRAG_ELEMENT.style.transition = '';
      DRAG_ELEMENT.style.transform = '';
      DRAG_ELEMENT.style.opacity = '';
      return;
    }
    const dx = e.changedTouches[0].clientX - touchStartX;
    const dy = e.changedTouches[0].clientY - touchStartY;
    const elapsed = Date.now() - touchStartTime;
    const isMostlyHorizontal = Math.abs(dx) > Math.abs(dy) * 1.5;
    const isFarEnough = dx > THRESHOLD;
    const isFastEnough = elapsed < 600;

    DRAG_ELEMENT.style.transition = 'transform .22s ease, opacity .22s ease';
    if (isMostlyHorizontal && isFarEnough && isFastEnough) {
      committed = true;
      DRAG_ELEMENT.style.transform = 'translateX(100%)';
      DRAG_ELEMENT.style.opacity = '0';
      setTimeout(() => { window.location.href = '/workspace.html'; }, 220);
    } else {
      DRAG_ELEMENT.style.transform = 'translateX(0)';
      DRAG_ELEMENT.style.opacity = '1';
      setTimeout(() => {
        if (!committed) { DRAG_ELEMENT.style.transition = ''; DRAG_ELEMENT.style.transform = ''; DRAG_ELEMENT.style.opacity = ''; }
      }, 230);
    }
  }, { passive: true });

  // A gesture can be interrupted (an incoming call, switching apps
  // mid-swipe) without ever firing touchend -- without this, content
  // could get stuck permanently dragged partway off-screen.
  document.body.addEventListener('touchcancel', () => {
    if (!dragging || !visuallyDragged) return;
    dragging = false;
    DRAG_ELEMENT.style.transition = 'transform .22s ease, opacity .22s ease';
    DRAG_ELEMENT.style.transform = 'translateX(0)';
    DRAG_ELEMENT.style.opacity = '1';
    setTimeout(() => { DRAG_ELEMENT.style.transition = ''; DRAG_ELEMENT.style.transform = ''; DRAG_ELEMENT.style.opacity = ''; }, 230);
  });
}

